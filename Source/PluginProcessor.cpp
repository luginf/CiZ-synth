void CZ101Processor::startEngineIfNeeded()
{
    if (currentSampleRate <= 0.0 || currentBlockSize.load() <= 0 || std::atomic_load (&engine) != nullptr)
        return;

    lastError.clear();
    const auto roms = getRomsDirectory();
    if (! hasRomSet (roms))
    {
        lastError = getMachineLabel() + " ROM (" + machine + ".zip/.7z/folder) not found in " + roms.getFullPathName();
        state.store (static_cast<int> (EngineState::MissingRom));
        return;
    }

    const auto plugins = resolvePluginsDirectory();
    if (! plugins.isDirectory())
    {
        lastError = "MAME plugins (boot.lua, layout/init.lua) not found";
        state.store (static_cast<int> (EngineState::Failed));
        return;
    }

    const auto cfgDir = juce::File::getSpecialLocation (juce::File::tempDirectory).getChildFile ("CiZ-synth-cfg");
    cfgDir.deleteRecursively();
    const auto nvramDir = getNvramDirectory();
    if (! cfgDir.createDirectory() || ! nvramDir.createDirectory())
    {
        lastError = "Could not create the cfg/nvram folders";
        state.store (static_cast<int> (EngineState::Failed));
        return;
    }

    ves::EmbeddedEmulatorEngineSettings settings;
    settings.rom_path = buildRomStage (roms).getFullPathName().toStdString();
    settings.cfg_path = cfgDir.getFullPathName().toStdString();
    settings.nvram_path = nvramDir.getFullPathName().toStdString();
    settings.plugins_path = plugins.getFullPathName().toStdString();
    // Custom panel artwork exists for the CZ-101 only; the CZ-1 uses MAME's built-in layout.
    if (const auto artwork = resolveArtworkDirectory(); machine == "cz101" && artwork.isDirectory())
        settings.artwork_path = artwork.getFullPathName().toStdString();
    settings.driver_name = machine.toStdString();
    settings.sample_rate = static_cast<int> (std::lround (currentSampleRate));
    settings.native_midi_input_option = "midiin";   // cz101 has a real MIDI IN port
    // The CZ-1 has two MIDI OUT ports (OUT and THRU), so MAME numbers them: midiout1 is OUT.
    settings.native_midi_output_option = machine == "cz1" ? "midiout1" : "midiout";
    settings.engine_generation = engineGeneration.load() + 1;
    settings.save_nvram = true;                      // keep the internal patches

    auto newEngine = std::make_shared<ves::EmbeddedEmulatorEngine> (std::move (settings));
    newEngine->setVideoDisplayActive (true);
    newEngine->requestVideoCaptureWidth (requestedCaptureWidth.load());
    newEngine->start();
    newEngine->noteHostAudioConfiguration (currentSampleRate, currentBlockSize.load());

    std::atomic_store (&engine, std::move (newEngine));
    engineGeneration.fetch_add (1);
    bootStartMs = juce::Time::getMillisecondCounter();
    state.store (static_cast<int> (EngineState::Booting));
    logLine ("engine started, generation " + juce::String (static_cast<juce::int64> (engineGeneration.load())));
}

void CZ101Processor::stopEngine()
{
    const auto oldEngine = std::atomic_exchange (&engine, std::shared_ptr<ves::EmbeddedEmulatorEngine> {});
    if (oldEngine != nullptr)
        logLine ("stopping engine");
    if (oldEngine != nullptr)
        oldEngine->stopAndJoin (std::chrono::seconds (5));

    if (getEngineState() != EngineState::MissingRom)
        state.store (static_cast<int> (EngineState::Stopped));
}

void CZ101Processor::restartEngine()
{
    const juce::ScopedLock sl (engineLock);
    stopEngine();
    startEngineIfNeeded();
}

// Collects what the emulated synth sends on MIDI OUT.  After one quiet second the
// capture is written to <app data>/midi-out.bin and summarised in the log, so a
// panel-triggered dump (MIDI Save) can be inspected.
void CZ101Processor::captureMidiOutput()
{
    const auto localEngine = std::atomic_load (&engine);
    if (localEngine == nullptr)
        return;

    std::uint8_t buffer[1024];
    for (;;)
    {
        const auto count = localEngine->readMidiOutput (buffer, sizeof buffer);
        if (count == 0)
            break;
        midiOutCapture.insert (midiOutCapture.end(), buffer, buffer + count);
        midiOutLastByteMs = juce::Time::getMillisecondCounter();
    }

    if (! midiOutCapture.empty() && juce::Time::getMillisecondCounter() - midiOutLastByteMs > 1000)
    {
        const auto file = appDataDirectory().getChildFile ("midi-out.bin");
        file.replaceWithData (midiOutCapture.data(), midiOutCapture.size());

        juce::String head;
        for (size_t i = 0; i < midiOutCapture.size() && i < 16; ++i)
            head << juce::String::toHexString (midiOutCapture[i]).paddedLeft ('0', 2) << " ";
        logLine ("MIDI OUT: " + juce::String (static_cast<juce::int64> (midiOutCapture.size())) + " bytes, starts " + head
                 + "-> " + file.getFullPathName());
        const auto dump = cz::parseDump (midiOutCapture);
        bool any = false;
        for (auto present : dump.present)
            any = any || present;
        if (any)
        {
            {
                const juce::ScopedLock lock (dumpLock);
                latestDump = dump;
            }
            dumpGeneration.fetch_add (1);
        }
        midiOutCapture.clear();
    }
}

void CZ101Processor::sendSysex (const std::vector<std::uint8_t>& message)
{
    if (sysexFifo.getFreeSpace() < static_cast<int> (message.size()))
        return;

    int s1, n1, s2, n2;
    sysexFifo.prepareToWrite (static_cast<int> (message.size()), s1, n1, s2, n2);
    std::copy_n (message.begin(), n1, sysexStorage.begin() + s1);
    if (n2 > 0)
        std::copy_n (message.begin() + n1, n2, sysexStorage.begin() + s2);
    sysexFifo.finishedWrite (n1 + n2);
}

bool CZ101Processor::isToneMemoryAvailable() const
{
    const auto localEngine = std::atomic_load (&engine);
    return machine == "cz1" && localEngine != nullptr && getEngineState() == EngineState::Ready;
}

bool CZ101Processor::readInternalTone (int slot, cz::Tone& tone) const
{
    const auto localEngine = std::atomic_load (&engine);
    if (! isToneMemoryAvailable() || slot < 0 || slot >= 64)
        return false;

    return localEngine->readRam ("subram", static_cast<std::size_t> (cz::bodySize * slot), tone.data.data(), cz::bodySize) == cz::bodySize
        && localEngine->readRam ("mainram", static_cast<std::size_t> (2304 + 16 * slot), tone.data.data() + cz::bodySize, cz::nameSize) == cz::nameSize;
}

bool CZ101Processor::writeInternalTone (int slot, const cz::Tone& tone)
{
    const auto localEngine = std::atomic_load (&engine);
    if (! isToneMemoryAvailable() || slot < 0 || slot >= 64)
        return false;

    return localEngine->writeRam ("subram", static_cast<std::size_t> (cz::bodySize * slot), tone.data.data(), cz::bodySize) == cz::bodySize
        && localEngine->writeRam ("mainram", static_cast<std::size_t> (2304 + 16 * slot), tone.data.data() + cz::bodySize, cz::nameSize) == cz::nameSize;
}

void CZ101Processor::recallInternalTone (int slot)
{
    sendSysex ({ 0xC0, static_cast<std::uint8_t> (juce::jlimit (0, 63, slot)) });
}

bool CZ101Processor::getLatestDump (cz::Dump& out) const
{
    const juce::ScopedLock lock (dumpLock);
    out = latestDump;
    return true;
}

void CZ101Processor::timerCallback()
{
    updateBootState();
    captureMidiOutput();

    const auto localEngine = std::atomic_load (&engine);
    if (localEngine == nullptr || getEngineState() != EngineState::Ready)
    {
        rateLogLastTime = 0.0;
        return;
    }

    const auto now = juce::Time::getMillisecondCounterHiRes() * 0.001;
    const auto mame = localEngine->diagnostics().audio_frames_written.load();
    const auto device = deviceFramesRendered.load();
    if (rateLogLastTime == 0.0)
    {
        rateLogLastTime = now;
        rateLogLastMame = mame;
        rateLogLastDevice = device;
        return;
    }

    const auto elapsed = now - rateLogLastTime;
    if (elapsed < 5.0)
        return;

    const auto mameRate = static_cast<double> (mame - rateLogLastMame) / elapsed;
    const auto deviceRate = static_cast<double> (device - rateLogLastDevice) / elapsed;
    logLine ("audio: MAME " + juce::String (mameRate, 1) + " fr/s, placa " + juce::String (deviceRate, 1)
             + " fr/s, diferenca " + juce::String (juce::roundToInt ((mameRate / deviceRate - 1.0) * 1.0e6)) + " ppm"
             + " | latencia " + juce::String (jitterBuffer.getLatencyMs(), 1) + " ms, ajuste "
             + juce::String (jitterBuffer.getRatioPpm()) + " ppm, falhas "
             + juce::String (static_cast<juce::int64> (jitterBuffer.getUnderruns())) + ", descartes "
             + juce::String (static_cast<juce::int64> (jitterBuffer.getDiscards()))
             + ", margem " + juce::String (jitterBuffer.getMarginMs(), 1) + " ms"
             + ", bloco MAME " + juce::String (static_cast<juce::int64> (localEngine->diagnostics().mame_audio_callback_block_size.load())));

    rateLogLastTime = now;
    rateLogLastMame = mame;
    rateLogLastDevice = device;
}

void CZ101Processor::updateBootState()
{
    if (getEngineState() != EngineState::Booting)
        return;

    const auto localEngine = std::atomic_load (&engine);
    if (localEngine == nullptr)
        return;

    const auto& diag = localEngine->diagnostics();
    static int bootTicks = 0;
    if (++bootTicks % 10 == 0)
        logLine ("boot: " + juce::String (juce::Time::getMillisecondCounter() - bootStartMs) + " ms, started="
                 + juce::String (static_cast<juce::int64> (diag.machine_started.load())) + " frames="
                 + juce::String (static_cast<juce::int64> (diag.video_frames_produced.load())) + " exited="
                 + juce::String (static_cast<juce::int64> (diag.machine_exited.load())));
    if (diag.machine_exited.load() != 0)
    {
        lastError = "MAME exited during boot (code " + juce::String (localEngine->mameResult()) + ")";
        state.store (static_cast<int> (EngineState::Failed));
        return;
    }

    if (juce::Time::getMillisecondCounter() - bootStartMs < minimumBootMs
        || diag.machine_started.load() == 0
        || diag.video_frames_produced.load() == 0)
        return;

    // Throw away audio generated while booting; the jitter buffer re-primes from here.
    localEngine->discardQueuedAudio();
    state.store (static_cast<int> (EngineState::Ready));
    logLine ("ready");
}

juce::String CZ101Processor::getStatusText() const
{
    switch (getEngineState())
    {
        case EngineState::Stopped:    return "Stopped (waiting for audio device)";
        case EngineState::MissingRom: return lastError;
        case EngineState::Booting:    return "Starting " + getMachineLabel() + "...";
        case EngineState::Ready:      return "Ready";
        case EngineState::Failed:     return "Failed: " + lastError;
    }
    return {};
}

juce::String CZ101Processor::getAudioDiagnosticsText() const
{
    if (getEngineState() != EngineState::Ready)
        return {};

    const auto ppm = jitterBuffer.getRatioPpm();
    return "buffer " + juce::String (currentBlockSize.load())
         + " | latency " + juce::String (juce::roundToInt (jitterBuffer.getLatencyMs())) + " ms"
         + " | adjust " + (ppm > 0 ? "+" : "") + juce::String (ppm) + " ppm"
         + " | underruns " + juce::String (static_cast<juce::int64> (jitterBuffer.getUnderruns()));
}

