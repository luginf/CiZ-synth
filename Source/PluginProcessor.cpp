bool CZ101Processor::hasRomSet (const juce::File& directory) const
{
    return directory.getChildFile ("cz101.zip").existsAsFile()
        || directory.getChildFile ("cz101.7z").existsAsFile()
        || directory.getChildFile ("cz101").isDirectory();
}

juce::File CZ101Processor::getRomsDirectory() const
{
    return juce::File (romsPath);
}

juce::File CZ101Processor::getNvramDirectory() const
{
    return appDataDirectory().getChildFile ("nvram");
}

void CZ101Processor::setRomsDirectory (const juce::File& directory)
{
    if (! directory.isDirectory())
        return;

    romsPath = directory.getFullPathName();
    saveSettings();
    restartEngine();
}

juce::File CZ101Processor::getSettingsFile() const
{
    return appDataDirectory().getChildFile ("settings.xml");
}

void CZ101Processor::saveSettings() const
{
    juce::XmlElement xml ("CZ101Studio");
    xml.setAttribute ("romsPath", romsPath);
    const auto file = getSettingsFile();
    file.getParentDirectory().createDirectory();
    xml.writeTo (file);
}

