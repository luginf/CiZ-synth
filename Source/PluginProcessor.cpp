// MAME reports the machine as started a little before the firmware is ready
// for MIDI; give it a moment after the first rendered frame.
constexpr juce::uint32 minimumBootMs = 2000;

// juce::String (const char*) treats literals as ASCII; accented text needs this.
juce::String utf8 (const char* text)
{
    return juce::String::fromUTF8 (text);
}

void logLine (const juce::String& text)
{
#if JUCE_MAC
    const auto logFile = juce::File::getSpecialLocation (juce::File::userHomeDirectory)
                             .getChildFile ("Library/Logs/CiZ-synth.log");
#else
    const auto logFile = juce::File::getSpecialLocation (juce::File::userApplicationDataDirectory)
                             .getChildFile ("CiZ-synth").getChildFile ("CiZ-synth.log");
#endif
    static juce::FileLogger logger (logFile, "CiZ-synth", 512 * 1024);
    logger.logMessage (juce::Time::getCurrentTime().toString (false, true, true, true) + "  " + text);
}

// JUCE's userApplicationDataDirectory is ~/Library on macOS, not Application Support.
juce::File appDataDirectory()
{
#if JUCE_MAC
    return juce::File::getSpecialLocation (juce::File::userApplicationDataDirectory)
        .getChildFile ("Application Support").getChildFile ("CiZ-synth");
#else
    // ~/.config/CiZ-synth
    return juce::File::getSpecialLocation (juce::File::userApplicationDataDirectory)
        .getChildFile ("CiZ-synth");
#endif
}

// Folder holding the bundled plugins/ and artwork/ directories.
juce::File bundledResourcesDirectory()
{
    const auto app = juce::File::getSpecialLocation (juce::File::currentApplicationFile);
#if JUCE_MAC
    return app.getChildFile ("Contents").getChildFile ("Resources");
#else
    return app.getParentDirectory().getChildFile ("Resources");
#endif
}

// Kept outside ~/Documents: macOS asks for Documents access again after every
// rebuild (new ad-hoc signature) and MAME blocks on the ROM open until answered.
juce::File defaultRomsDirectory()
{
    return appDataDirectory().getChildFile ("roms");
}

juce::File resolvePluginsDirectory()
{
    const auto isValid = [] (const juce::File& dir)
    {
        return dir.getChildFile ("boot.lua").existsAsFile()
            && dir.getChildFile ("layout").getChildFile ("init.lua").existsAsFile();
    };

    // CiZ-synth.app/Contents/Resources/plugins
    const auto bundled = bundledResourcesDirectory().getChildFile ("plugins");
    if (isValid (bundled))
        return bundled;

    const auto source = juce::File (CIZ_SOURCE_RESOURCES).getChildFile ("plugins");
    return isValid (source) ? source : juce::File {};
}

// MAME -artpath root holding cz101/default.lay.  The project folder wins over the
// bundled copy so artwork regenerated by tools/make_artwork.py shows up after
// pressing "Restart", without rebuilding the app.
juce::File resolveArtworkDirectory()
{
    const auto isValid = [] (const juce::File& dir)
    {
        return dir.getChildFile ("cz101").getChildFile ("default.lay").existsAsFile();
    };

    const auto source = juce::File (CIZ_SOURCE_RESOURCES).getChildFile ("artwork");
    if (isValid (source))
        return source;

    const auto bundled = bundledResourcesDirectory().getChildFile ("artwork");
    return isValid (bundled) ? bundled : juce::File {};
}
