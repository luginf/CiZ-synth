void CZ101Processor::processBlock (juce::AudioBuffer<float>& buffer, juce::MidiBuffer& midi)
{
    juce::ScopedNoDenormals noDenormals;
    buffer.clear();

    const auto localEngine = std::atomic_load (&engine);
    const auto ready = localEngine != nullptr && getEngineState() == EngineState::Ready;

    keyboardState.processNextMidiBuffer (midi, 0, buffer.getNumSamples(), true);

    // SysEx queued by the tone editor goes in first, so it is never interleaved with notes.
    {
        const auto ready2 = localEngine != nullptr && getEngineState() == EngineState::Ready;
        const auto start1 = sysexFifo.getNumReady();
        if (start1 > 0)
        {
            int s1, n1, s2, n2;
            sysexFifo.prepareToRead (start1, s1, n1, s2, n2);
            if (ready2)
            {
                if (n1 > 0) localEngine->sendMidiBytes (sysexStorage.data() + s1, static_cast<std::size_t> (n1));
                if (n2 > 0) localEngine->sendMidiBytes (sysexStorage.data() + s2, static_cast<std::size_t> (n2));
            }
            sysexFifo.finishedRead (n1 + n2);
        }
    }

    for (const auto metadata : midi)
    {
        const auto* data = metadata.data;
        const auto size = metadata.numBytes;
        if (size <= 0 || data[0] == 0xf8 || data[0] == 0xfe) // clock / active sensing
            continue;

        lastMidiInMs.store (juce::Time::getMillisecondCounter());
        midiMessagesReceived.fetch_add (1);

        if (! ready)
        {
            midiDroppedBeforeReady.fetch_add (1);
            continue;
        }

        localEngine->sendMidiBytes (data, static_cast<std::size_t> (size));
    }

    const auto generation = engineGeneration.load();
    if (generation != jitterBufferGeneration)
    {
        jitterBuffer.reset();
        jitterBufferGeneration = generation;
    }

    if (! ready)
        return;

    const auto numSamples = buffer.getNumSamples();
    const auto channels = buffer.getNumChannels();
    if (channels == 0 || (channels == 1 && numSamples > static_cast<int> (monoScratch.size())))
        return;

    auto* left = buffer.getWritePointer (0);
    auto* right = channels > 1 ? buffer.getWritePointer (1) : monoScratch.data();
    deviceFramesRendered.fetch_add (static_cast<uint64_t> (numSamples));
    if (offline.load())
    {
        renderizarOffline (*localEngine, left, right, numSamples);
    }
    else if (! jitterBuffer.render (*localEngine, left, right, numSamples))
    {
        buffer.clear();
        return;
    }

    if (machineIsCz1.load() && chorusEnabled.load())
        chorus.process (left, right, numSamples);

    float blockPeak[2] { 0.0f, 0.0f };
    for (int i = 0; i < numSamples; ++i)
    {
        blockPeak[0] = juce::jmax (blockPeak[0], std::abs (left[i]));
        blockPeak[1] = juce::jmax (blockPeak[1], std::abs (right[i]));
        if (channels == 1)
            left[i] = 0.5f * (left[i] + right[i]);
    }

    for (int ch = 0; ch < 2; ++ch)
    {
        auto previous = peak[ch].load();
        while (blockPeak[ch] > previous && ! peak[ch].compare_exchange_weak (previous, blockPeak[ch]))
        {
        }
    }
}

float CZ101Processor::takePeak (int channel)
{
    return peak[juce::jlimit (0, 1, channel)].exchange (0.0f);
}

