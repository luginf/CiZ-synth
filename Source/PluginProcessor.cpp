bool CZ101Processor::copyLatestVideoFrame (VideoFrame& frame)
{
    const auto localEngine = std::atomic_load (&engine);
    if (localEngine == nullptr)
        return false;

    ves::VideoFrameSnapshot snapshot;
    if (! localEngine->copyLatestVideoFrame (snapshot))
        return false;

    frame.width = snapshot.width;
    frame.height = snapshot.height;
    frame.generation = snapshot.generation;
    frame.engineGeneration = engineGeneration.load();
    frame.pixels = std::move (snapshot.pixels);
    return true;
}

void CZ101Processor::requestVideoCaptureWidth (int width)
{
    const auto quantized = juce::jlimit (1024, 4096, ((juce::jmax (width, 1) + 63) / 64) * 64);
    requestedCaptureWidth.store (quantized);
    if (const auto localEngine = std::atomic_load (&engine))
        localEngine->requestVideoCaptureWidth (quantized);
}

void CZ101Processor::enqueueMouseEvent (ves::EmbeddedMouseEventType type, int x, int y)
{
    if (const auto localEngine = std::atomic_load (&engine))
        localEngine->enqueueMouseEvent (type, x, y);
}

void CZ101Processor::requestMouseRelease()
{
    if (const auto localEngine = std::atomic_load (&engine))
        localEngine->requestMouseRelease();
}

