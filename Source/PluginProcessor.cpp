bool CZ101Processor::hasRomSet (const juce::File& directory) const
{
    return directory.getChildFile (machine + ".zip").existsAsFile()
        || directory.getChildFile (machine + ".7z").existsAsFile()
        || directory.getChildFile (machine).isDirectory()
        || ! directory.findChildFiles (juce::File::findFiles, false, "*.bin").isEmpty();
}

// MAME only reads loose ROM files from a folder named after the set (cz1/,
// hd44780/).  Build a folder of symlinks that accepts, for each needed set, a
// .zip, a .7z, a set folder, or loose .bin files sitting next to them.
juce::File CZ101Processor::buildRomStage (const juce::File& romsDirectory) const
{
    const auto stage = appDataDirectory().getChildFile ("romstage");
    stage.deleteRecursively();
    if (! stage.createDirectory())
        return romsDirectory;

    const auto looseFiles = romsDirectory.findChildFiles (juce::File::findFiles, false, "*.bin");

    for (const juce::String set : { machine, juce::String ("hd44780") })
    {
        bool found = false;
        for (const auto* extension : { ".zip", ".7z" })
        {
            const auto archive = romsDirectory.getChildFile (set + extension);
            if (archive.existsAsFile())
                found = archive.createSymbolicLink (stage.getChildFile (set + extension), true) || found;
        }

        const auto folder = romsDirectory.getChildFile (set);
        if (folder.isDirectory())
            found = folder.createSymbolicLink (stage.getChildFile (set), true) || found;

        if (! found && ! looseFiles.isEmpty())
        {
            // MAME also matches by CRC, so original file names are not required.
            const auto setFolder = stage.getChildFile (set);
            setFolder.createDirectory();
            for (const auto& file : looseFiles)
                file.createSymbolicLink (setFolder.getChildFile (file.getFileName()), true);
        }
    }

    return stage;
}

