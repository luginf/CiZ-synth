void CZ101Processor::startEngineIfNeeded()
{
    if (currentSampleRate <= 0.0 || currentBlockSize.load() <= 0 || std::atomic_load (&engine) != nullptr)
        return;

    lastError.clear();
    const auto roms = getRomsDirectory();
    if (! hasRomSet (roms))
    {
        lastError = utf8 ("ROM cz101 (.zip/.7z/pasta) não encontrada em ") + roms.getFullPathName();
        state.store (static_cast<int> (EngineState::MissingRom));
        return;
    }

    const auto plugins = resolvePluginsDirectory();
    if (! plugins.isDirectory())
    {
        lastError = utf8 ("Plugins MAME (boot.lua, layout/init.lua) não encontrados");
        state.store (static_cast<int> (EngineState::Failed));
        return;
    }

    const auto cfgDir = juce::File::getSpecialLocation (juce::File::tempDirectory).getChildFile ("CZ101Studio-cfg");
    cfgDir.deleteRecursively();
    const auto nvramDir = getNvramDirectory();
    if (! cfgDir.createDirectory() || ! nvramDir.createDirectory())
    {
        lastError = utf8 ("Não foi possível criar as pastas de cfg/nvram");
        state.store (static_cast<int> (EngineState::Failed));
        return;
    }

    ves::EmbeddedEmulatorEngineSettings settings;
    settings.rom_path = roms.getFullPathName().toStdString();
    settings.cfg_path = cfgDir.getFullPathName().toStdString();
    settings.nvram_path = nvramDir.getFullPathName().toStdString();
    settings.plugins_path = plugins.getFullPathName().toStdString();
    if (const auto artwork = resolveArtworkDirectory(); artwork.isDirectory())
        settings.artwork_path = artwork.getFullPathName().toStdString();
    settings.driver_name = driverName;
    settings.sample_rate = static_cast<int> (std::lround (currentSampleRate));
    settings.native_midi_input_option = "midiin";   // cz101 has a real MIDI IN port
    settings.engine_generation = engineGeneration.load() + 1;
    settings.save_nvram = true;                      // keep the internal patches

    auto newEngine = std::make_shared<ves::EmbeddedEmulatorEngine> (std::move (settings));
    newEngine->setVideoDisplayActive (true);
    newEngine->requestVideoCaptureWidth (requestedCaptureWidth.load());
    newEngine->start();
    newEngine->noteHostAudioConfiguration (currentSampleRate, currentBlockSize.load());

    std::atomic_store (&engine, std::move (newEngine));
    engineGeneration.fetch_add (1);
    bootStartMs = juce::Time::getMillisecondCounter();
    state.store (static_cast<int> (EngineState::Booting));
    logLine ("motor iniciado, geracao " + juce::String (static_cast<juce::int64> (engineGeneration.load())));
}

void CZ101Processor::stopEngine()
{
    const auto oldEngine = std::atomic_exchange (&engine, std::shared_ptr<ves::EmbeddedEmulatorEngine> {});
    if (oldEngine != nullptr)
        logLine ("parando motor");
    if (oldEngine != nullptr)
        oldEngine->stopAndJoin (std::chrono::seconds (5));

    if (getEngineState() != EngineState::MissingRom)
        state.store (static_cast<int> (EngineState::Stopped));
}

void CZ101Processor::restartEngine()
{
    const juce::ScopedLock sl (engineLock);
    stopEngine();
    startEngineIfNeeded();
}

void CZ101Processor::timerCallback()
{
    updateBootState();

    const auto localEngine = std::atomic_load (&engine);
    if (localEngine == nullptr || getEngineState() != EngineState::Ready)
    {
        rateLogLastTime = 0.0;
        return;
    }

    const auto now = juce::Time::getMillisecondCounterHiRes() * 0.001;
    const auto mame = localEngine->diagnostics().audio_frames_written.load();
    const auto device = deviceFramesRendered.load();
    if (rateLogLastTime == 0.0)
    {
        rateLogLastTime = now;
        rateLogLastMame = mame;
        rateLogLastDevice = device;
        return;
    }

    const auto elapsed = now - rateLogLastTime;
    if (elapsed < 5.0)
        return;

    const auto mameRate = static_cast<double> (mame - rateLogLastMame) / elapsed;
    const auto deviceRate = static_cast<double> (device - rateLogLastDevice) / elapsed;
    logLine ("audio: MAME " + juce::String (mameRate, 1) + " fr/s, placa " + juce::String (deviceRate, 1)
             + " fr/s, diferenca " + juce::String (juce::roundToInt ((mameRate / deviceRate - 1.0) * 1.0e6)) + " ppm"
             + " | latencia " + juce::String (jitterBuffer.getLatencyMs(), 1) + " ms, ajuste "
             + juce::String (jitterBuffer.getRatioPpm()) + " ppm, falhas "
             + juce::String (static_cast<juce::int64> (jitterBuffer.getUnderruns())) + ", descartes "
             + juce::String (static_cast<juce::int64> (jitterBuffer.getDiscards()))
             + ", margem " + juce::String (jitterBuffer.getMarginMs(), 1) + " ms"
             + ", bloco MAME " + juce::String (static_cast<juce::int64> (localEngine->diagnostics().mame_audio_callback_block_size.load())));

    rateLogLastTime = now;
    rateLogLastMame = mame;
    rateLogLastDevice = device;
}

void CZ101Processor::updateBootState()
{
    if (getEngineState() != EngineState::Booting)
        return;

    const auto localEngine = std::atomic_load (&engine);
    if (localEngine == nullptr)
        return;

    const auto& diag = localEngine->diagnostics();
    static int bootTicks = 0;
    if (++bootTicks % 10 == 0)
        logLine ("boot: " + juce::String (juce::Time::getMillisecondCounter() - bootStartMs) + " ms, started="
                 + juce::String (static_cast<juce::int64> (diag.machine_started.load())) + " frames="
                 + juce::String (static_cast<juce::int64> (diag.video_frames_produced.load())) + " exited="
                 + juce::String (static_cast<juce::int64> (diag.machine_exited.load())));
    if (diag.machine_exited.load() != 0)
    {
        lastError = utf8 ("MAME encerrou durante o boot (código ") + juce::String (localEngine->mameResult()) + ")";
        state.store (static_cast<int> (EngineState::Failed));
        return;
    }

    if (juce::Time::getMillisecondCounter() - bootStartMs < minimumBootMs
        || diag.machine_started.load() == 0
        || diag.video_frames_produced.load() == 0)
        return;

    // Throw away audio generated while booting; the jitter buffer re-primes from here.
    localEngine->discardQueuedAudio();
    state.store (static_cast<int> (EngineState::Ready));
    logLine ("pronto");
}

juce::String CZ101Processor::getStatusText() const
{
    switch (getEngineState())
    {
        case EngineState::Stopped:    return utf8 ("Parado (aguardando dispositivo de áudio)");
        case EngineState::MissingRom: return lastError;
        case EngineState::Booting:    return "Iniciando CZ-101...";
        case EngineState::Ready:      return "Pronto";
        case EngineState::Failed:     return "Falhou: " + lastError;
    }
    return {};
}

juce::String CZ101Processor::getAudioDiagnosticsText() const
{
    if (getEngineState() != EngineState::Ready)
        return {};

    const auto ppm = jitterBuffer.getRatioPpm();
    return utf8 ("buffer ") + juce::String (currentBlockSize.load())
         + utf8 (" · latência ") + juce::String (juce::roundToInt (jitterBuffer.getLatencyMs())) + " ms"
         + utf8 (" · ajuste ") + (ppm > 0 ? "+" : "") + juce::String (ppm) + " ppm"
         + utf8 (" · falhas ") + juce::String (static_cast<juce::int64> (jitterBuffer.getUnderruns()));
}

