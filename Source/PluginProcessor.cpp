CZ101Processor::CZ101Processor()
    : AudioProcessor (BusesProperties().withOutput ("Output", juce::AudioChannelSet::stereo(), true))
{
    // Earlier builds kept their data in ~/Library/CZ101Studio: carry the saved patches over.
    const auto legacyNvram = juce::File::getSpecialLocation (juce::File::userHomeDirectory)
        .getChildFile ("Library").getChildFile ("CZ101Studio").getChildFile ("nvram");
    if (legacyNvram.isDirectory() && ! getNvramDirectory().isDirectory())
        legacyNvram.copyDirectoryTo (getNvramDirectory());

    const auto settings = getSettingsFile();
    if (auto xml = juce::XmlDocument::parse (settings))
        romsPath = xml->getStringAttribute ("romsPath");

    if (! juce::File (romsPath).isDirectory())
        romsPath = defaultRomsDirectory().getFullPathName();

    startTimerHz (10);
}

CZ101Processor::~CZ101Processor()
{
    stopTimer();
    stopEngine();
}

